"use client";

import { useState } from "react";
import {
  Activity,
  AlertTriangle,
  ArrowRight,
  Bot,
  CheckCircle2,
  Copy,
  Cpu,
  FileText,
  Flame,
  HardDrive,
  Play,
  Radio,
  RefreshCw,
  Send,
  ShieldAlert,
  Sparkles,
  Terminal,
  Zap,
} from "lucide-react";
import { useShellStore } from "@/store/ui-store";

type ChatMessage = {
  id: string;
  sender: "user" | "copilot";
  text: string;
  confidence?: number;
  artifact?: {
    type: string;
    title: string;
    code: string;
    lang: string;
  };
  suggestions?: string[];
  timestamp: string;
};

type PredictionItem = {
  id: string;
  target: string;
  component: string;
  probability: number;
  horizon: string;
  rootCause: string;
  action: string;
  status: "PREDICTED" | "RMA_SCHEDULED" | "RESOLVED";
};

const initialMessages: ChatMessage[] = [
  {
    id: "msg-1",
    sender: "copilot",
    text: "Hello! I am your Qnetward NetOps AI Copilot. I analyze real-time edge telemetry, PulseMesh gossip matrices, and eBPF socket events. Ask me to draft vendor ACLs, investigate packet loss anomalies, or generate executive post-mortems.",
    suggestions: [
      "Generate Cisco IOS-XE ACL to block CVE-2024-3400",
      "Draft Executive Post-Mortem for Frankfurt Transit Outage",
      "Investigate Singapore Edge Packet Loss Spike",
    ],
    timestamp: "Just now",
  },
];

const samplePredictions: PredictionItem[] = [
  {
    id: "pred-opt-104",
    target: "core-router-1:Te0/1/1",
    component: "SFP+ Optical Transceiver",
    probability: 0.94,
    horizon: "24-48 hours",
    rootCause: "Tx optical power degraded -2.4 dBm while laser bias current spiked +40% (30mA -> 42mA)",
    action: "Schedule proactive hot-swap replacement before hard link drop",
    status: "PREDICTED",
  },
  {
    id: "pred-buf-208",
    target: "spine-switch-fra-01",
    component: "Ingress Switch Buffer Pool",
    probability: 0.89,
    horizon: "12-24 hours",
    rootCause: "Ingress buffer headroom depleted (88.5% utilized) under 64 micro-bursts/sec",
    action: "Enable WRED/ECN dynamic QoS queue allocation to prevent drop storm",
    status: "PREDICTED",
  },
];

export function CopilotWorkspace() {
  const { locale } = useShellStore();
  const [activeTab, setActiveTab] = useState<"copilot" | "predictive">("copilot");
  const [messages, setMessages] = useState<ChatMessage[]>(initialMessages);
  const [inputPrompt, setInputPrompt] = useState("");
  const [isProcessing, setIsProcessing] = useState(false);
  const [predictions, setPredictions] = useState<PredictionItem[]>(samplePredictions);
  const [copiedId, setCopiedId] = useState<string | null>(null);

  const handleSendPrompt = (promptText?: string) => {
    const text = promptText || inputPrompt;
    if (!text.trim()) return;

    const userMsg: ChatMessage = {
      id: "usr-" + Date.now(),
      sender: "user",
      text,
      timestamp: "Just now",
    };

    setMessages(prev => [...prev, userMsg]);
    if (!promptText) setInputPrompt("");
    setIsProcessing(true);

    setTimeout(() => {
      const lower = text.toLowerCase();
      let copilotMsg: ChatMessage;

      if (lower.includes("cve") || lower.includes("acl") || lower.includes("block")) {
        copilotMsg = {
          id: "cop-" + Date.now(),
          sender: "copilot",
          text: "Generated a hardened Cisco IOS-XE extended access list to filter hostile ingress traffic matching the requested threat signature.",
          confidence: 0.98,
          artifact: {
            type: "CISCO_ACL",
            title: "Cisco IOS-XE Threat Mitigation ACL (CVE-2024-3400)",
            lang: "cisco",
            code: `! Cisco IOS-XE Extended Access Control List
! Generated by Qnetward NetOps Copilot for Threat Mitigation
ip access-list extended QNETWARD_THREAT_BLOCK_V4
 10 remark Drop telemetry and exploits matching CVE vulnerability signature
 20 deny tcp any any eq 443 match-all +ack +psh
 30 deny tcp any any eq 8443
 40 deny udp any any range 50000 50100
 50 permit ip any any
!
! Apply to ingress border interface:
interface TenGigabitEthernet0/1/0
 ip access-group QNETWARD_THREAT_BLOCK_V4 in
!`,
          },
          suggestions: [
            "Dry-run verify ACL against simulated digital twin topology",
            "Deploy via Autonomous Playbook with operator approval",
            "Configure mirrored SPAN port for forensic traffic capture",
          ],
          timestamp: "Just now",
        };
      } else if (lower.includes("post-mortem") || lower.includes("postmortem") || lower.includes("report")) {
        copilotMsg = {
          id: "cop-" + Date.now(),
          sender: "copilot",
          text: "Synthesized an executive post-mortem incident report based on correlated telemetry, optical DOM metrics, and autonomous playbook remediation logs.",
          confidence: 0.95,
          artifact: {
            type: "POSTMORTEM_REPORT",
            title: "Executive Incident Post-Mortem (INC-89104)",
            lang: "markdown",
            code: `# Executive Incident Post-Mortem
**Incident ID**: INC-89104  
**Date**: 2026-10-31  
**Severity**: P1 - High Availability Impact  
**Affected Infrastructure**: Frankfurt Core Transit Gateway (fra-core-01)  

---

### 1. Executive Summary
At 14:15 UTC, the primary optical link on fra-core-01 experienced acute optical power degradation, triggering link flapping and a localized BGP alert storm. Qnetward AIOps automatically isolated the failing port and shifted 196 Gbps of transit traffic to the secondary Euro terrestrial backhaul.

### 2. Timeline & Root-Cause Analysis
- **14:12:10 UTC**: Optical DOM transceiver laser bias current drifted from 32mA to 48mA.
- **14:14:00 UTC**: Packet loss on primary link climbed from 0.01% to 8.4%.
- **14:15:30 UTC**: AI Root-Cause Engine correlated 14 downstream alerts into root incident INC-89104.
- **14:16:05 UTC**: Playbook rerouted BGP traffic; packet loss reduced to 0.00%.

### 3. Blast Radius
- Total traffic rerouted: **196 Gbps**
- Affected customer flows: **4 Enterprise VLANs**
- Net downtime: **0 seconds (sub-second autonomous path shift)**

### 4. Preventative Actions
- [x] Replace degraded SFP+ transceiver during scheduled maintenance.
- [x] Adjust optical DOM predictive drift warning threshold to 36 hours.`,
          },
          suggestions: [
            "Export executive report as signed PDF",
            "Publish post-mortem summary to #netops Slack channel",
            "Log cryptographic entry in Audit Ledger",
          ],
          timestamp: "Just now",
        };
      } else {
        copilotMsg = {
          id: "cop-" + Date.now(),
          sender: "copilot",
          text: "Telemetry correlation indicates localized packet loss on the edge switch was induced by transient upstream ISP micro-bursts rather than an internal link failure. Jitter and RTT percentiles on alternative paths remain within nominal SLA bounds.",
          confidence: 0.92,
          suggestions: [
            "Inspect switch buffer pool headroom",
            "Simulate traffic surge in Digital Twin",
            "Set proactive threshold alert on upstream CIR",
          ],
          timestamp: "Just now",
        };
      }

      setMessages(prev => [...prev, copilotMsg]);
      setIsProcessing(false);
    }, 700);
  };

  const handleCopyCode = (id: string, text: string) => {
    navigator.clipboard.writeText(text);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  const handleScheduleRMA = (id: string) => {
    setPredictions(prev =>
      prev.map(p => (p.id === id ? { ...p, status: "RMA_SCHEDULED" } : p))
    );
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-foreground flex items-center gap-2">
            <Sparkles className="h-7 w-7 text-indigo-500" />
            {locale === "bn"
              ? "নেটঅপস এআই কপাইলট ও প্রেডিক্টিভ অ্যানালিটিক্স"
              : "GenAI NetOps Copilot & Predictive Failure Analytics"}
          </h1>
          <p className="text-sm text-muted-foreground">
            {locale === "bn"
              ? "প্রাকৃতিক ভাষার নেটওয়ার্ক অ্যাসিস্ট্যান্ট, ভেন্ডর এসিএল জেনারেশন, পোস্ট-মর্টেম সিন্থেসিস এবং অপটিক্যাল লেজার ড্রিফট প্রেডিকশন।"
              : "Conversational NetOps AI assistant, automated ACL generation, incident post-mortems, and multivariate laser drift forecasting."}
          </p>
        </div>

        <div className="flex items-center gap-2">
          <span className="rounded-lg border border-indigo-500/30 bg-indigo-500/10 px-3 py-1.5 text-xs font-semibold text-indigo-400 flex items-center gap-1.5">
            <Bot className="h-4 w-4" />
            GenAI Pair-Engineer Online
          </span>
        </div>
      </div>

      {/* Tabs */}
      <div className="flex border-b border-border">
        <button
          onClick={() => setActiveTab("copilot")}
          className={`flex items-center gap-2 border-b-2 px-4 py-2.5 text-sm font-medium transition-colors ${
            activeTab === "copilot"
              ? "border-primary text-primary"
              : "border-transparent text-muted-foreground hover:text-foreground"
          }`}
        >
          <Bot className="h-4 w-4" />
          {locale === "bn" ? "নেটঅপস এআই কপাইলট" : "NetOps AI Copilot"}
        </button>
        <button
          onClick={() => setActiveTab("predictive")}
          className={`flex items-center gap-2 border-b-2 px-4 py-2.5 text-sm font-medium transition-colors ${
            activeTab === "predictive"
              ? "border-primary text-primary"
              : "border-transparent text-muted-foreground hover:text-foreground"
          }`}
        >
          <Flame className="h-4 w-4" />
          {locale === "bn" ? "প্রেডিক্টিভ ফেইলিউর মডেলিং" : "Predictive Failure Analytics"}
        </button>
      </div>

      {/* TAB 1: NetOps AI Copilot */}
      {activeTab === "copilot" && (
        <div className="space-y-4">
          {/* Quick Prompt Pills */}
          <div className="flex flex-wrap gap-2">
            {[
              "Generate Cisco IOS-XE ACL to block CVE-2024-3400",
              "Draft Executive Post-Mortem for Frankfurt Transit Outage",
              "Investigate Singapore Edge Packet Loss Spike",
            ].map((p, idx) => (
              <button
                key={idx}
                onClick={() => handleSendPrompt(p)}
                className="rounded-full border border-border bg-card px-3 py-1 text-xs text-muted-foreground hover:border-primary hover:text-foreground transition-colors"
              >
                {p}
              </button>
            ))}
          </div>

          {/* Chat Messages Container */}
          <div className="rounded-xl border border-border bg-card p-4 space-y-4 min-h-[420px] max-h-[580px] overflow-y-auto">
            {messages.map(msg => (
              <div
                key={msg.id}
                className={`flex flex-col ${msg.sender === "user" ? "items-end" : "items-start"}`}
              >
                <div
                  className={`max-w-[85%] rounded-xl p-3.5 text-sm space-y-2 ${
                    msg.sender === "user"
                      ? "bg-primary text-primary-foreground font-medium"
                      : "bg-background border border-border text-foreground"
                  }`}
                >
                  <div className="flex items-center justify-between gap-3 text-[11px] text-muted-foreground pb-1">
                    <span className="font-semibold flex items-center gap-1">
                      {msg.sender === "user" ? "Network Operator" : "NetOps AI Copilot"}
                    </span>
                    {msg.confidence && (
                      <span className="text-emerald-400 font-mono">
                        {(msg.confidence * 100).toFixed(0)}% Confidence
                      </span>
                    )}
                  </div>

                  <p className="whitespace-pre-wrap">{msg.text}</p>

                  {/* Artifact Box (Code / Report) */}
                  {msg.artifact && (
                    <div className="mt-2 rounded-lg border border-border bg-black text-foreground overflow-hidden">
                      <div className="flex items-center justify-between px-3 py-1.5 bg-muted/30 border-b border-border text-xs">
                        <span className="font-mono text-[11px] text-primary font-bold">
                          {msg.artifact.title}
                        </span>
                        <button
                          onClick={() => handleCopyCode(msg.id, msg.artifact?.code || "")}
                          className="flex items-center gap-1 text-[11px] text-muted-foreground hover:text-foreground"
                        >
                          <Copy className="h-3 w-3" />
                          {copiedId === msg.id ? "Copied!" : "Copy Code"}
                        </button>
                      </div>
                      <pre className="p-3 text-xs font-mono text-emerald-300 overflow-x-auto whitespace-pre">
                        {msg.artifact.code}
                      </pre>
                    </div>
                  )}

                  {/* Suggested Next Actions */}
                  {msg.suggestions && msg.suggestions.length > 0 && (
                    <div className="pt-2 border-t border-border/60 space-y-1">
                      <span className="text-[11px] font-semibold text-muted-foreground uppercase tracking-wider">
                        Suggested Next Steps:
                      </span>
                      <div className="flex flex-wrap gap-1.5">
                        {msg.suggestions.map((s, sIdx) => (
                          <span
                            key={sIdx}
                            className="rounded bg-muted px-2 py-0.5 text-[11px] font-medium text-foreground border border-border"
                          >
                            • {s}
                          </span>
                        ))}
                      </div>
                    </div>
                  )}
                </div>
              </div>
            ))}

            {isProcessing && (
              <div className="flex items-center gap-2 text-xs text-muted-foreground p-2">
                <RefreshCw className="h-4 w-4 animate-spin text-primary" />
                Synthesizing network telemetry and topology graphs...
              </div>
            )}
          </div>

          {/* Input Bar */}
          <div className="flex gap-2">
            <input
              type="text"
              value={inputPrompt}
              onChange={e => setInputPrompt(e.target.value)}
              onKeyDown={e => e.key === "Enter" && handleSendPrompt()}
              placeholder="Ask NetOps Copilot (e.g. 'Generate Juniper firewall filter to block DDoS port 53' or 'Explain latency spike')..."
              className="flex-1 rounded-lg border border-border bg-background px-4 py-2.5 text-sm text-foreground focus:outline-none focus:ring-1 focus:ring-primary font-sans"
            />
            <button
              onClick={() => handleSendPrompt()}
              disabled={isProcessing || !inputPrompt.trim()}
              className="flex items-center gap-2 rounded-lg bg-primary px-5 py-2.5 text-sm font-semibold text-primary-foreground hover:bg-primary/90 disabled:opacity-50"
            >
              <Send className="h-4 w-4" />
              Ask Copilot
            </button>
          </div>
        </div>
      )}

      {/* TAB 2: Predictive Failure Analytics */}
      {activeTab === "predictive" && (
        <div className="space-y-6">
          <div className="rounded-xl border border-border bg-card p-4 space-y-2">
            <h3 className="text-base font-semibold text-foreground flex items-center gap-2">
              <Flame className="h-5 w-5 text-red-400" />
              Multivariate Hardware Failure Radar (24-48h Pre-Failure Prediction)
            </h3>
            <p className="text-xs text-muted-foreground">
              Deep-learning models analyzing optical DOM laser power decay, bias current inflation, and switch packet buffer micro-burst patterns to forecast hardware death before production outages occur.
            </p>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            {predictions.map(pred => (
              <div key={pred.id} className="rounded-xl border border-border bg-card p-4 space-y-3">
                <div className="flex items-center justify-between border-b border-border pb-2.5">
                  <div>
                    <span className="text-[10px] font-bold uppercase tracking-wider text-red-400">
                      High Confidence Anomaly
                    </span>
                    <h4 className="text-base font-bold text-foreground font-mono">{pred.target}</h4>
                  </div>
                  <div className="text-right">
                    <span className="text-lg font-black text-red-400">
                      {(pred.probability * 100).toFixed(0)}%
                    </span>
                    <p className="text-[10px] text-muted-foreground">Failure Probability</p>
                  </div>
                </div>

                <div className="space-y-1.5 text-xs">
                  <div className="flex justify-between text-muted-foreground">
                    <span>Component:</span>
                    <span className="font-semibold text-foreground">{pred.component}</span>
                  </div>
                  <div className="flex justify-between text-muted-foreground">
                    <span>Predicted Horizon:</span>
                    <span className="font-bold text-amber-400">{pred.horizon}</span>
                  </div>
                  <div className="rounded-lg bg-background p-2.5 border border-border text-[11px] text-muted-foreground">
                    <span className="font-bold text-foreground">Root Cause Signal:</span> {pred.rootCause}
                  </div>
                  <div className="rounded-lg bg-background p-2.5 border border-border text-[11px] text-primary">
                    <span className="font-bold text-foreground">Action:</span> {pred.action}
                  </div>
                </div>

                <div className="pt-2 flex items-center justify-between">
                  <span className={`px-2.5 py-1 rounded text-xs font-bold ${
                    pred.status === "RMA_SCHEDULED"
                      ? "bg-emerald-500/20 text-emerald-300 border border-emerald-500/40"
                      : "bg-red-500/20 text-red-300 border border-red-500/40"
                  }`}>
                    {pred.status === "RMA_SCHEDULED" ? "RMA SCHEDULED" : "ACTION REQUIRED"}
                  </span>

                  {pred.status === "PREDICTED" && (
                    <button
                      onClick={() => handleScheduleRMA(pred.id)}
                      className="rounded-lg bg-primary px-3 py-1.5 text-xs font-semibold text-primary-foreground hover:bg-primary/90"
                    >
                      Schedule Hot-Swap RMA
                    </button>
                  )}
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}
