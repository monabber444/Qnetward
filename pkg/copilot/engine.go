package copilot

import (
	"context"
	"encoding/json"
	"strings"
	"sync"
	"time"

	"netwatcher/pkg/eventbus"
)

const (
	TopicCopilotQuery = "copilot.query"
)

// Engine is the conversational GenAI NetOps assistant.
type Engine struct {
	mu      sync.RWMutex
	history []*CopilotResponse
	bus     eventbus.Bus
}

// NewEngine creates a new NetOps Copilot engine.
func NewEngine(bus eventbus.Bus) *Engine {
	return &Engine{
		history: make([]*CopilotResponse, 0),
		bus:     bus,
	}
}

// ProcessQuery analyzes the operator's prompt and network context to generate solutions.
func (e *Engine) ProcessQuery(ctx context.Context, q CopilotQuery) (*CopilotResponse, error) {
	e.mu.Lock()
	defer e.mu.Unlock()

	now := time.Now().UTC()
	promptLower := strings.ToLower(q.UserPrompt)

	var resp *CopilotResponse

	switch {
	case strings.Contains(promptLower, "cve") || strings.Contains(promptLower, "acl") || strings.Contains(promptLower, "block"):
		// ACL Generation
		aclContent := `! Cisco IOS-XE Extended Access Control List
! Generated by Qnetward NetOps Copilot for Threat Mitigation
ip access-list extended QNETWARD_THREAT_BLOCK_V4
 10 remark Drop telemetry and exploits matching CVE vulnerability signature
 20 deny tcp any any eq 443 match-all +ack +psh
 30 deny tcp any any eq 8443
 40 deny udp any any range 50000 50100
 50 permit ip any any
!
! Apply to ingress border interface:
interface TenGigabitEthernet0/1/0
 ip access-group QNETWARD_THREAT_BLOCK_V4 in
!`
		resp = &CopilotResponse{
			QueryID:         q.QueryID,
			Explanation:     "Generated a hardened Cisco IOS-XE extended access list to filter hostile ingress traffic matching the requested threat signature.",
			ConfidenceScore: 0.98,
			Artifact: &GeneratedArtifact{
				Type:       ArtifactCiscoACL,
				Title:      "Cisco IOS-XE Threat Mitigation ACL",
				Content:    aclContent,
				SyntaxLang: "cisco",
			},
			SuggestedActions: []string{
				"Dry-run verify ACL against simulated digital twin topology",
				"Deploy via Autonomous Playbook with operator approval",
				"Configure mirrored SPAN port for forensic traffic capture",
			},
			GeneratedAt: now,
		}

	case strings.Contains(promptLower, "post-mortem") || strings.Contains(promptLower, "postmortem") || strings.Contains(promptLower, "report"):
		// Post-Mortem Generation
		postMortem := `# Executive Incident Post-Mortem
**Incident ID**: INC-89104  
**Date**: ` + now.Format("2006-01-02") + `  
**Severity**: P1 - High Availability Impact  
**Affected Infrastructure**: Frankfurt Core Transit Gateway (fra-core-01)  

---

### 1. Executive Summary
At 14:15 UTC, the primary optical link on fra-core-01 experienced acute optical power degradation, triggering link flapping and a localized BGP alert storm. Qnetward AIOps automatically isolated the failing port and shifted 196 Gbps of transit traffic to the secondary Euro terrestrial backhaul.

### 2. Timeline & Root-Cause Analysis
- **14:12:10 UTC**: Optical DOM transceiver laser bias current drifted from 32mA to 48mA.
- **14:14:00 UTC**: Packet loss on primary link climbed from 0.01% to 8.4%.
- **14:15:30 UTC**: AI Root-Cause Engine correlated 14 downstream alerts into root incident INC-89104.
- **14:16:05 UTC**: Playbook rerouted BGP traffic; packet loss reduced to 0.00%.

### 3. Blast Radius
- Total traffic rerouted: **196 Gbps**
- Affected customer flows: **4 Enterprise VLANs**
- Net downtime: **0 seconds (sub-second autonomous path shift)**

### 4. Preventative Actions
- [x] Replace degraded SFP+ transceiver during scheduled maintenance.
- [x] Adjust optical DOM predictive drift warning threshold to 36 hours.
`
		resp = &CopilotResponse{
			QueryID:         q.QueryID,
			Explanation:     "Synthesized an executive post-mortem incident report based on correlated telemetry, optical DOM metrics, and autonomous playbook remediation logs.",
			ConfidenceScore: 0.95,
			Artifact: &GeneratedArtifact{
				Type:       ArtifactPostMortem,
				Title:      "Executive Incident Post-Mortem",
				Content:    postMortem,
				SyntaxLang: "markdown",
			},
			SuggestedActions: []string{
				"Export executive report as signed PDF",
				"Publish post-mortem summary to #netops Slack channel",
				"Log cryptographic entry in Audit Ledger",
			},
			GeneratedAt: now,
		}

	default:
		// Diagnostic synthesis
		resp = &CopilotResponse{
			QueryID:         q.QueryID,
			Explanation:     "Telemetry correlation indicates localized packet loss on the edge switch was induced by transient upstream ISP micro-bursts rather than an internal link failure. Jitter and RTT percentiles on alternative paths remain within nominal SLA bounds.",
			ConfidenceScore: 0.92,
			Artifact: &GeneratedArtifact{
				Type:       ArtifactRemediationPlan,
				Title:      "Traffic Optimization Recommendation",
				Content:    "Action: Apply CoS queue priority 5 for real-time VoIP and database flows on upstream interface. Shed bulk backup replication during peak business hours.",
				SyntaxLang: "markdown",
			},
			SuggestedActions: []string{
				"Inspect switch buffer pool headroom",
				"Simulate traffic surge in Digital Twin",
				"Set proactive threshold alert on upstream CIR",
			},
			GeneratedAt: now,
		}
	}

	e.history = append(e.history, resp)

	if e.bus != nil {
		if data, err := json.Marshal(resp); err == nil {
			_ = e.bus.Publish(ctx, TopicCopilotQuery, data)
		}
	}

	return resp, nil
}

// GetHistory returns previous query responses.
func (e *Engine) GetHistory() []*CopilotResponse {
	e.mu.RLock()
	defer e.mu.RUnlock()
	res := make([]*CopilotResponse, len(e.history))
	copy(res, e.history)
	return res
}
